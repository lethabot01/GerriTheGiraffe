#!/usr/bin/env node
/* Lists the recorded voice clips in assets/voices/ so the cartoon can find them.
 *   node scripts/build-voice-manifest.js
 * Clip files are named by line id (see docs/voice-lines.md), e.g. assets/voices/ep01/ep01-s01-b00.mp3.
 * .mp3, .m4a, .ogg and .wav all work. */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'voices');
const clips = {};
const walk = d => fs.readdirSync(d, { withFileTypes: true }).forEach(e => {
  const p = path.join(d, e.name);
  if (e.isDirectory()) return walk(p);
  const m = /^(ep\d\d-s\d\d-b\d\d(?:-a)?)\.(mp3|m4a|ogg|wav)$/i.exec(e.name);
  if (m) clips[m[1]] = path.relative(dir, p).split(path.sep).join('/');
});
walk(dir);
const sorted = Object.fromEntries(Object.entries(clips).sort());
fs.writeFileSync(path.join(dir, 'manifest.js'),
  `/* Recorded voice clips. Generated by scripts/build-voice-manifest.js; do not edit by hand.\n * Maps a line id (see docs/voice-lines.md) to its file inside assets/voices/. */\nwindow.VOICE_CLIPS = ${JSON.stringify(sorted, null, 2)};\n`);
console.log(`Found ${Object.keys(sorted).length} voice clips.`);
